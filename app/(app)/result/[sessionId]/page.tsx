'use client'

import { useState, useEffect } from 'react'
import { useParams } from 'next/navigation'
import { type SessionData, type Advice } from '@/lib/schemas'
import { generateAdvicePDF } from '@/lib/pdf'
import { PDFDownloadLink } from '@react-pdf/renderer'

export default function ResultPage() {
  const params = useParams()
  const sessionId = params.sessionId as string
  const [sessionData, setSessionData] = useState<SessionData | null>(null)
  const [advice, setAdvice] = useState<Advice | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    fetchSessionData()
  }, [sessionId])

  const fetchSessionData = async () => {
    try {
      const response = await fetch(`/api/sessions/${sessionId}`)
      if (!response.ok) {
        throw new Error('Session not found')
      }
      
      const data = await response.json()
      setSessionData(data.session)
      
      // Convert session data to advice format
      const adviceData: Advice = {
        severity: data.session.severity as 'STOP' | 'LIMIT' | 'OK',
        driveability: data.session.summary,
        causes: data.session.insights.map((insight: any) => ({
          cause: insight.label,
          why: insight.why,
          confidence: insight.confidence
        })),
        checks: data.session.insights[0]?.steps || [],
        notes: 'Generated by Lumara Auto AI Triage System'
      }
      setAdvice(adviceData)
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to load session')
    } finally {
      setLoading(false)
    }
  }

  const getSeverityColor = (severity: string) => {
    switch (severity) {
      case 'STOP': return 'bg-red-600'
      case 'LIMIT': return 'bg-yellow-500'
      case 'OK': return 'bg-green-600'
      default: return 'bg-gray-600'
    }
  }

  const getSeverityText = (severity: string) => {
    switch (severity) {
      case 'STOP': return 'STOP - Do Not Drive'
      case 'LIMIT': return 'LIMIT - Drive with Caution'
      case 'OK': return 'OK - Safe to Drive'
      default: return severity
    }
  }

  if (loading) {
    return (
      <div className="min-h-screen bg-gray-50 flex items-center justify-center">
        <div className="text-center">
          <div className="animate-spin rounded-full h-12 w-12 border-b-2 border-blue-600 mx-auto mb-4"></div>
          <p className="text-gray-600">Loading your results...</p>
        </div>
      </div>
    )
  }

  if (error || !sessionData || !advice) {
    return (
      <div className="min-h-screen bg-gray-50 flex items-center justify-center">
        <div className="text-center">
          <h1 className="text-2xl font-bold text-gray-900 mb-4">Error</h1>
          <p className="text-gray-600 mb-4">{error || 'Session not found'}</p>
          <a href="/check" className="text-blue-600 hover:text-blue-800">Start a new check</a>
        </div>
      </div>
    )
  }

  return (
    <div className="min-h-screen bg-gray-50">
      <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8 py-8">
        {/* Header */}
        <div className="text-center mb-8">
          <h1 className="text-3xl font-bold text-gray-900 mb-2">Your Car Triage Results</h1>
          <p className="text-gray-600">Generated on {new Date(sessionData.createdAt).toLocaleDateString()}</p>
        </div>

        {/* Severity Badge */}
        <div className={`${getSeverityColor(advice.severity)} text-white text-center py-4 rounded-lg mb-8`}>
          <h2 className="text-2xl font-bold">{getSeverityText(advice.severity)}</h2>
        </div>

        {/* Safety Message */}
        {advice.severity === 'STOP' && (
          <div className="bg-red-50 border border-red-200 rounded-lg p-4 mb-8">
            <div className="flex">
              <div className="flex-shrink-0">
                <svg className="h-5 w-5 text-red-400" viewBox="0 0 20 20" fill="currentColor">
                  <path fillRule="evenodd" d="M10 18a8 8 0 100-16 8 8 0 000 16zM8.707 7.293a1 1 0 00-1.414 1.414L8.586 10l-1.293 1.293a1 1 0 101.414 1.414L10 11.414l1.293 1.293a1 1 0 001.414-1.414L11.414 10l1.293-1.293a1 1 0 00-1.414-1.414L10 8.586 8.707 7.293z" clipRule="evenodd" />
                </svg>
              </div>
              <div className="ml-3">
                <h3 className="text-sm font-medium text-red-800">Critical Safety Warning</h3>
                <div className="mt-2 text-sm text-red-700">
                  <p>Do not drive your vehicle. This condition requires immediate attention from a qualified mechanic.</p>
                </div>
              </div>
            </div>
          </div>
        )}

        {/* Driveability */}
        <div className="bg-white rounded-lg shadow p-6 mb-8">
          <h2 className="text-xl font-semibold text-gray-900 mb-4">Can I Drive?</h2>
          <p className="text-gray-700 leading-relaxed">{advice.driveability}</p>
        </div>

        {/* Likely Causes */}
        <div className="bg-white rounded-lg shadow p-6 mb-8">
          <h2 className="text-xl font-semibold text-gray-900 mb-6">Likely Causes (Ranked by Probability)</h2>
          <div className="space-y-4">
            {advice.causes.map((cause, index) => (
              <div key={index} className="border border-gray-200 rounded-lg p-4">
                <div className="flex justify-between items-start mb-2">
                  <h3 className="text-lg font-medium text-gray-900">
                    {index + 1}. {cause.cause}
                  </h3>
                  <span className="text-sm text-gray-500">
                    {Math.round(cause.confidence * 100)}% confidence
                  </span>
                </div>
                <p className="text-gray-600 text-sm">{cause.why}</p>
              </div>
            ))}
          </div>
        </div>

        {/* Safe Checks */}
        <div className="bg-white rounded-lg shadow p-6 mb-8">
          <h2 className="text-xl font-semibold text-gray-900 mb-6">Safe Checks You Can Do</h2>
          <div className="space-y-3">
            {advice.checks.map((check, index) => (
              <div key={index} className="flex items-start">
                <input
                  type="checkbox"
                  className="mt-1 h-4 w-4 text-blue-600 focus:ring-blue-500 border-gray-300 rounded"
                />
                <span className="ml-3 text-gray-700">{check}</span>
              </div>
            ))}
          </div>
        </div>

        {/* Mechanic Checklist */}
        <div className="bg-blue-50 border border-blue-200 rounded-lg p-6 mb-8">
          <h2 className="text-xl font-semibold text-blue-900 mb-4">What to Tell Your Mechanic</h2>
          <div className="space-y-3">
            <div>
              <h3 className="font-medium text-blue-800 mb-2">Symptoms to Report:</h3>
              <ul className="text-blue-700 text-sm space-y-1">
                {sessionData.symptoms.map((symptom, index) => (
                  <li key={index}>• {symptom.value}</li>
                ))}
              </ul>
            </div>
            <div>
              <h3 className="font-medium text-blue-800 mb-2">Likely Causes to Investigate:</h3>
              <ul className="text-blue-700 text-sm space-y-1">
                {advice.causes.slice(0, 3).map((cause, index) => (
                  <li key={index}>• {cause.cause}</li>
                ))}
              </ul>
            </div>
            <div>
              <h3 className="font-medium text-blue-800 mb-2">Checks to Perform:</h3>
              <ul className="text-blue-700 text-sm space-y-1">
                {advice.checks.slice(0, 3).map((check, index) => (
                  <li key={index}>• {check}</li>
                ))}
              </ul>
            </div>
          </div>
        </div>

        {/* Actions */}
        <div className="flex flex-col sm:flex-row gap-4 justify-center">
          <PDFDownloadLink
            document={generateAdvicePDF(sessionData, advice)}
            fileName={`car-triage-${sessionId}.pdf`}
            className="bg-blue-600 text-white px-6 py-3 rounded-lg font-semibold hover:bg-blue-700 transition-colors text-center"
          >
            Download PDF Report
          </PDFDownloadLink>
          <a
            href="/check"
            className="border border-gray-300 text-gray-700 px-6 py-3 rounded-lg font-semibold hover:bg-gray-50 transition-colors text-center"
          >
            Start New Check
          </a>
        </div>

        {/* Disclaimer */}
        <div className="mt-8 text-center text-sm text-gray-500">
          <p>
            This report is for informational purposes only. Always consult a qualified mechanic for professional diagnosis and repair.
          </p>
        </div>
      </div>
    </div>
  )
}
